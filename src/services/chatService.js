/**
 * NORA Chat Service
 * 
 * Coordinates sending user messages either to the real Python/Gemma backend
 * or to the local compassionate mock generator, ensuring a completely functional
 * and resilient demo experience without fake claims.
 */

import { checkBackendStatus, postChatMessageToBackend, apiConfig } from "./api";
import { generateLocalMockResponse } from "../data/mockChatResponses";

class ChatService {
  constructor() {
    this.backendStatus = {
      isOnline: false,
      mode: "local_mock",
      message: "Checking connection..."
    };
    this.checkedAt = null;
  }

  /**
   * Initializes or refreshes the backend connection status.
   */
  async updateStatus() {
    this.backendStatus = await checkBackendStatus();
    this.checkedAt = new Date();
    return this.backendStatus;
  }

  getStatus() {
    return this.backendStatus;
  }

  /**
   * Sends a message and returns NORA's response.
   * If remote backend is unreachable, automatically uses local mock responses.
   *
   * @param {string} userMessage 
   * @param {Array} history 
   * @param {Object} context 
   * @returns {Promise<{ text: string, actionSuggestion?: Object, source: string, note?: string }>}
   */
  async sendMessage(userMessage, history = [], context = {}) {
    // If backend is configured and not forced to mock, try it first
    if (!apiConfig.forceMock) {
      try {
        const backendReply = await postChatMessageToBackend(userMessage, history, context);
        return {
          ...backendReply,
          source: "backend",
          note: "Generated by connected Python backend."
        };
      } catch (err) {
        console.info(
          "Python backend unavailable or failed. Falling back to local mock responses:",
          err.message
        );
        // Update cached status to reflect offline
        this.backendStatus = {
          isOnline: false,
          mode: "local_mock",
          message: "Python backend unreachable; using local mock responses."
        };
      }
    }

    // Local mock generator with gentle realistic delay
    await new Promise((resolve) => setTimeout(resolve, 650));
    const mockReply = generateLocalMockResponse(userMessage, context);

    return {
      text: mockReply.text,
      actionSuggestion: mockReply.actionSuggestion || null,
      source: "local_mock",
      note: "Local demo response. Ready for Gemma/Python backend."
    };
  }
}

export const chatService = new ChatService();
